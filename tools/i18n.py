# Chinese (Taiwan) / Korean text for the game. The source is i18n.json at the repo root: { "<Japanese text>": {"zh": "...", "ko": "..."} }.
# build.py calls write() so src/0_i18n.js always matches i18n.json. New Japanese text without a translation falls back to English
# and is listed by qa/i18n_audit.js; add it to i18n.json (same rules as docs/I18N.md) and build again.
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def ko_punct(t):
  # Korean does not use the Japanese middle dot or corner brackets: ・ → ·, 「…」 → ‘…’ (found on the Korean screens, 2026-11-08)
  return t.replace('・', '·').replace('「', '‘').replace('」', '’').replace('『', '“').replace('』', '”')
def write():
  d = json.load(open(os.path.join(ROOT, 'i18n.json'), encoding='utf-8'))
  zh = {k: v['zh'] for k, v in d.items() if v.get('zh')}; ko = {k: ko_punct(v['ko']) for k, v in d.items() if v.get('ko')}
  js = ('/* ================= Chinese (Taiwan) and Korean: the Japanese text is the key; anything missing falls back to English =================\n'
        '   Generated by tools/i18n.py from i18n.json (docs/I18N.md). Do not edit by hand. The same four languages as the official site. */\n'
        'const I18N = ' + json.dumps({'zh': zh, 'ko': ko}, ensure_ascii=False, separators=(',', ':')) + ';\n')
  open(os.path.join(ROOT, 'src', '0_i18n.js'), 'w', encoding='utf-8').write(js)
  return len(zh), len(ko)
if __name__ == '__main__': print(write())
